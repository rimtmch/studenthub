-- 1. Ensure columns exist on 'profiles' so Admin can view/reset student passwords
ALTER TABLE profiles 
  ADD COLUMN IF NOT EXISTS role text DEFAULT 'student',
  ADD COLUMN IF NOT EXISTS is_admin boolean DEFAULT false,
  ADD COLUMN IF NOT EXISTS password text,
  ADD COLUMN IF NOT EXISTS pin text,
  ADD COLUMN IF NOT EXISTS avatar text,
  ADD COLUMN IF NOT EXISTS course text DEFAULT 'MBBS',
  ADD COLUMN IF NOT EXISTS batch_year text DEFAULT '2024',
  ADD COLUMN IF NOT EXISTS phone text,
  ADD COLUMN IF NOT EXISTS dob text;

-- 2. Create 'reports' table for flagging posts & Admin Moderation Queue
CREATE TABLE IF NOT EXISTS reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  confession_id bigint NOT NULL,
  reason text NOT NULL,
  reporter_username text NOT NULL,
  created_at timestamptz DEFAULT now()
);

-- 3. Enable Row Level Security (RLS) on 'reports'
ALTER TABLE reports ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public select on reports" ON reports;
CREATE POLICY "Allow public select on reports" ON reports FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert on reports" ON reports;
CREATE POLICY "Allow public insert on reports" ON reports FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete on reports" ON reports;
CREATE POLICY "Allow public delete on reports" ON reports FOR DELETE USING (true);

-- 4. Ensure deletion and update permissions on 'confessions' so Admin can moderate
ALTER TABLE confessions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public select on confessions" ON confessions;
CREATE POLICY "Allow public select on confessions" ON confessions FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert on confessions" ON confessions;
CREATE POLICY "Allow public insert on confessions" ON confessions FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update on confessions" ON confessions;
CREATE POLICY "Allow public update on confessions" ON confessions FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow public delete on confessions" ON confessions;
CREATE POLICY "Allow public delete on confessions" ON confessions FOR DELETE USING (true);

